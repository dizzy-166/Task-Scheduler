# Regex-замены (применяются после литеральных)
REGEX = [
    # Backend / Frontend (одиночные слова)
    (r'\bBackend\b',   'Серверная часть'),
    (r'\bbackend\b',   'серверная часть'),
    (r'\bFrontend\b',  'Клиентская часть'),
    (r'\bfrontend\b',  'клиентская часть'),
    # AI (одиночное, без дефиса)
    (r'\bAI\b',        'ИИ'),
    # LLM
    (r'\bLLM\b',       'языковая модель'),
    # WIP (остаток)
    (r'\bWIP\b',       'незавершённые задачи'),
    # CDN
    (r'\bCDN\b',       'сеть доставки контента'),
    # HMR
    (r'\bHMR\b',       'горячую замену модулей'),
    # стор (с Cyrillic word-boundary через (?<!\w))
    (r'(?<![а-яёА-ЯЁ\w])стор(?![а-яёА-ЯЁ\w])', 'хранилище состояния'),
    # velocity
    (r'\bvelocity\b',  'скорость команды'),
    # stand-up (одиночный)
    (r'\bstand-up\b',  'ежедневное совещание'),
    # kanban (строчной)
    (r'\bkanban\b',    'канбан'),
]


def apply_all(text: str) -> str:
    """Apply literal then regex replacements to a plain text string."""
    for old, new in LITERAL:
        text = text.replace(old, new)
    for pattern, new in REGEX:
        text = re.sub(pattern, new, text)
    return text


def process_xml(xml: str) -> str:
    """Apply replacements only inside <w:t>…</w:t> tags."""
    def replacer(m):
        opening = m.group(1)
        content = m.group(2)
        closing = m.group(3)
        return opening + apply_all(content) + closing

    return re.sub(r'(<w:t[^>]*>)([^<]*)(</w:t>)', replacer, xml)


def repack(unpacked_dir: str, out_docx: str):
    tmp = out_docx + ".tmp"
    with zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as zf:
        for root, _dirs, files in os.walk(unpacked_dir):
            for fname in files:
                fpath = os.path.join(root, fname)
                arcname = os.path.relpath(fpath, unpacked_dir)
                zf.write(fpath, arcname)
    if os.path.exists(out_docx):
        os.remove(out_docx)
    os.rename(tmp, out_docx)


def main():
    print(f"Reading: {XML}")
    with open(XML, 'r', encoding='utf-8') as f:
        xml = f.read()

    xml_new = process_xml(xml)

    changes = xml_new != xml
    print(f"Text changed: {changes}")

    with open(XML, 'w', encoding='utf-8') as f:
        f.write(xml_new)
    print("XML written back.")

    print(f"Repacking → {DOCX}")
    repack(UNPACKED, DOCX)
    print("Done.")


if __name__ == '__main__':
    main()
